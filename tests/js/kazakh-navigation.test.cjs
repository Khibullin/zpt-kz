const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('static/interface/navigation.js','utf8');
const dictionary = JSON.parse(source.match(/const translations = (\{.*?\});/)[1]);
const functionSource = source.slice(source.indexOf('function translate('),source.indexOf("document.addEventListener('click'"));
const node = {nodeType:3,textContent:'  Подбор по автомобилю  '};
const technical = {nodeType:3,textContent:'Audi 100 C4 4A0959455C'};
const original = {nodeType:3,textContent:'Описание'};
const el = n => ({childNodes:[n],closest:selector=>n===original && selector.includes('[data-no-translate]')});
const input = {placeholder:'Артикул или название запчасти',dataset:{}};
const document = {documentElement:{},querySelectorAll:()=>[]};
const root = {querySelectorAll:selector=>selector==='input[placeholder],textarea[placeholder]'?[input]:selector.startsWith('label,')?[el(node),el(technical),el(original)]:[]};
const context=vm.createContext({document,lang:'kk',translations:dictionary,originals:new WeakMap()});
vm.runInContext(functionSource,context);context.translate(root);
assert.equal(node.textContent,'  Автомобиль бойынша таңдау  ');
assert.equal(technical.textContent,'Audi 100 C4 4A0959455C');
assert.equal(original.textContent,'Описание');
assert.equal(input.placeholder,'Артикул немесе бөлшек атауы');
context.lang='ru';context.translate(root);
assert.equal(node.textContent,'  Подбор по автомобилю  ');
assert.equal(input.placeholder,'Артикул или название запчасти');
context.lang='kk';context.translate(root);context.translate(root);
assert.equal(node.textContent,'  Автомобиль бойынша таңдау  ');
assert.equal(dictionary['Амортизатор задний R газомасляный ESCE 51945'],'Артқы оң жақ газ-майлы амортизатор ESCE 51945');
console.log('Kazakh UI: toggle, repeat, placeholders, technical identifiers and original source passed');
