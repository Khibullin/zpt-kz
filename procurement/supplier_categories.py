"""Preliminary categories from supplier descriptions; no applicability inference."""
import re

# Specific combinations precede general component names.
RULES = (
    ('Опора амортизатора', r'опор.*(?:амортиз|стойк)|(?:амортиз|стойк).*опор'),
    ('Стойка стабилизатора', r'стойк.*стабилиз|стабилиз.*стойк'),
    ('Рулевой наконечник', r'наконечник.*рулев|рулев.*наконечник'),
    ('Рулевая тяга', r'тяг.*рулев|рулев.*тяг'),
    ('Шаровая опора', r'шаров'), ('Шрус (граната)', r'шрус|гранат'),
    ('Диск тормозной', r'диск.*тормоз|тормоз.*диск'),
    ('Колодки', r'колодк'), ('Амортизатор', r'амортиз'),
    ('Рычаг', r'рычаг'), ('Пружина', r'пружин|spring'),
    ('Фильтр', r'фильтр|filter'), ('Свеча', r'свеч'),
    ('Подшипник', r'подшипник|bearing'), ('Сайлентблок', r'сайлент'),
    ('Ремень', r'ремен'), ('Прокладка', r'прокладк'),
    ('Радиатор', r'радиатор'), ('Термостат', r'термостат'),
    ('Насос', r'насос|помпа'), ('Датчик', r'датчик'),
    ('Пыльник', r'пыльник'), ('Втулка', r'втулк'),
    ('Сальник', r'сальник'), ('Ступица', r'ступиц'),
)

def classify_name(name):
    text = str(name or '').casefold()
    for category, pattern in RULES:
        if re.search(pattern, text):
            return category
    return 'Без категории'
