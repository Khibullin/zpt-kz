def iter_faq_items():
    for section in FAQ_SECTIONS:
        for item in section['items']:
            yield section, item


def faq_item_count() -> int:
    return sum(len(section['items']) for section in FAQ_SECTIONS)


def faq_prompt_block() -> str:
    lines = [
        'Проверенные ответы раздела «ZPT Гид».',
        'Опирайся на них и не противоречь им.',
        'Не выдумывай комиссии, тарифы, сроки ответа, способы оплаты и условия возврата.',
        'Если условие задаёт продавец — так и скажи.',
        'Комплекты ТО: состав только у конкретного набора; масло и свечи входят не во все наборы.',
        'Публичное название раздела: «ZPT Гид».',
        '',
    ]
    for section, item in iter_faq_items():
        lines.append(f"Вопрос ({section['title']}): {item['question']}")
        lines.append(f"Ответ: {item['answer']}")
        if item['links']:
            link_text = '; '.join(f'{label} — https://zpt.kz{url}' for url, label in item['links'])
            lines.append(f'Ссылки: {link_text}')
        lines.append('')
    return '\n'.join(lines).strip()
